export class Login {
  private readonly api = inject(Api);
  private readonly router = inject(Router);
  private readonly route = inject(ActivatedRoute);
  readonly expired = this.route.snapshot.queryParamMap.has('expired');
  readonly form = inject(FormBuilder).nonNullable.group({
    username: ['', Validators.required],
    password: ['', Validators.required],
  });
  readonly busy = signal(false);
  readonly error = signal('');
  async submit(): Promise<void> {
    if (this.busy()) return;
    this.form.markAllAsTouched();
    if (this.form.invalid) {
      this.error.set('Enter your username and password.');
      return;
    }
    this.error.set('');
    this.busy.set(true);
    try {
      const values = this.form.getRawValue();
      await this.api.login(values.username, values.password);
      this.form.controls.password.reset();
      const target = this.route.snapshot.queryParamMap.get('returnUrl') ?? '/overview';
      await this.router.navigateByUrl(
        /^\/(overview|employees)(\b|\/|\?)/.test(target) ? target : '/overview',
      );
    } catch (error) {
      this.error.set(problem(error).detail ?? 'Sign-in failed.');
    } finally {
      this.busy.set(false);
    }
  }
}
